export function districtById(id) {
  return DISTRICTS.find((district) => district.id === id) || DISTRICTS[0];
}

export function propertyById(id) {
  return PROPERTIES.find((property) => property.id === id) || null;
}

export function tickerBySymbol(symbol) {
  return TICKERS.find((ticker) => ticker.symbol === symbol) || TICKERS[0];
}
